"""
物理常量定义模块

所有常量均使用模拟单位（Simulation Units）：
- G = 1（无量纲引力常数）
- MU = 1（质量单位）
- DU = 1（距离单位）
- TU = 1（时间单位，由 G, MU, DU 导出）
"""

# ============================================================
# 核心物理常量（模拟单位）
# ============================================================

# 万有引力常数（模拟单位中 G=1）
G = 1.0

# 软化因子，防止引力计算中的奇点（当距离趋近于0时）
# 单位：DU
SOFTENING = 0.01

# ============================================================
# 碰撞参数
# ============================================================

# 碰撞检测的距离阈值系数（两 physical_radius 之和的倍数）
COLLISION_FACTOR = 1.0

# 合并后半径计算方式：基于体积守恒
# V = (4/3)pi*r^3，合并后体积 = 体积1 + 体积2
# r_new = (r1^3 + r2^3)^(1/3)
RADIUS_MERGE_EXPONENT = 1.0 / 3.0

# ============================================================
# 时间参数
# ============================================================

# 默认时间步长
# 单位：TU
DEFAULT_DT = 0.001  # 约 60 FPS

# ============================================================
# 轨迹参数
# ============================================================

# 轨迹历史记录最大长度
MAX_TRAJECTORY_LENGTH = 1000

# ============================================================
# 默认视觉尺度参数（模拟单位）
# ============================================================

# 默认摄像机视野范围（DU）
DEFAULT_VIEW_X_RANGE = (-20.0, 20.0)   # X: -20 ~ +20 DU
DEFAULT_VIEW_Y_RANGE = (-15.0, 15.0)   # Y: -15 ~ +15 DU

# 默认天体参数（用于 UI 预设）
DEFAULT_CENTRAL_STAR_MASS = 1000.0     # MU
DEFAULT_PLANET_MASS = 1.0              # MU
DEFAULT_ORBIT_DISTANCE = 10.0          # DU
# 圆轨道速度 = sqrt(G * M / r) = sqrt(1000 / 10) = 10 DU/TU
DEFAULT_ORBITAL_VELOCITY = 10.0        # DU/TU
